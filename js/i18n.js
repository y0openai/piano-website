  function detectInitialLang() {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored && SUPPORTED.includes(stored)) return stored;
    const browser = (navigator.language || navigator.userLanguage || '').toLowerCase();
    if (browser.startsWith('ko')) return 'ko';
    return DEFAULT_LANG;
  }

  function tr(lang, key) {
    const dict = T[lang] || T[DEFAULT_LANG];
    if (Object.prototype.hasOwnProperty.call(dict, key)) return dict[key];
    if (T[DEFAULT_LANG] && Object.prototype.hasOwnProperty.call(T[DEFAULT_LANG], key)) {
      return T[DEFAULT_LANG][key];
    }
    return null;
  }

  function applyLang(lang) {
    document.documentElement.setAttribute('lang', lang);

    // <title>
    const titleKey = document.documentElement.getAttribute('data-i18n-title');
    if (titleKey) {
      const t = tr(lang, titleKey);
      if (t !== null) document.title = t;
    }

    // textContent
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const k = el.getAttribute('data-i18n');
      const t = tr(lang, k);
      if (t !== null) el.textContent = t;
    });

    // innerHTML
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      const k = el.getAttribute('data-i18n-html');
      const t = tr(lang, k);
      if (t !== null) el.innerHTML = t;
    });

    // attributes
    document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
      const spec = el.getAttribute('data-i18n-attr');
      spec.split(';').forEach((pair) => {
        const [attr, key] = pair.split(':').map((s) => s.trim());
        if (!attr || !key) return;
        const t = tr(lang, key);
        if (t !== null) el.setAttribute(attr, t);
      });
    });

    // toggle button states
    document.querySelectorAll('.lang-toggle__btn').forEach((b) => {
      b.classList.toggle('active', b.dataset.lang === lang);
    });
  }

  const listeners = [];
  function emit(lang) {
    listeners.forEach((fn) => {
      try { fn(lang); } catch (e) { /* swallow */ }
    });
  }

  function setLang(lang) {
    if (!SUPPORTED.includes(lang)) lang = DEFAULT_LANG;
    localStorage.setItem(STORAGE_KEY, lang);
    applyLang(lang);
    emit(lang);
  }

  function init() {
    const lang = detectInitialLang();
    applyLang(lang);
    emit(lang);
    document.querySelectorAll('.lang-toggle__btn').forEach((b) => {
      b.addEventListener('click', () => setLang(b.dataset.lang));
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }

